export type EmailTranslationKey = keyof typeof emailTranslations.el
export type EmailLanguage = keyof typeof emailTranslations

export const getEmailTranslation = (key: EmailTranslationKey, language: EmailLanguage = 'el'): string => {
  return emailTranslations[language][key] || emailTranslations.en[key] || key
}

export const formatEmailText = (text: string, variables: Record<string, string | number>): string => {
  return text.replace(/\{(\w+)\}/g, (match, key) => {
    return variables[key]?.toString() || match
  })
}
